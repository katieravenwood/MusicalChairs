const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const c=vm.createContext({Date,Intl,JSON,Set,Map});
for(const f of ['apps-script/Core.gs','apps-script/authenticated/Editor.gs','apps-script/authenticated/AdminWeb.gs','demo/runtime.js'])vm.runInContext(fs.readFileSync(f,'utf8'),c);
c.seedDemo('2026-11-01');
let state=c.demoCall('getEditorState');assert(state.isAdmin);assert(state.rows.length>0);
const first=state.rows.find(r=>r.chairId==='keys');
const req={...first,playerId:'SamBrown',status:'Confirmed',unavailable:['AlexSmith'],note:'Pickup'};
vm.runInContext("demoIdentity='sambrown@example.invalid'",c);
state=c.demoCall('getEditorState');assert(!state.isAdmin);assert(state.chairs.every(c=>c.chairId==='keys'));
const before=c.demoPublicData().events;
c.demoCall('saveEditorAssignment',req);
assert.throws(()=>c.demoCall('saveEditorAssignment',req),/changed/);
assert.throws(()=>c.demoCall('getAdminState'),/Administrators only/);
const after=c.demoPublicData().events;
assert.equal(after.filter((e,i)=>e.playerId!==before[i].playerId).length,1);
assert(after.find(e=>e.performanceId===first.performanceId&&e.chair==='Keys 2').unavailablePlayerIds.includes('AlexSmith'));
assert.throws(()=>c.demoCall('saveEditorAssignment',{...req,chairId:'drums'}),/cannot edit/);
const snap=c.demoSnapshot('SamBrown');assert(snap.includes('BEGIN:VEVENT'));assert(!snap.includes(' - Drums - '));
assert.notEqual(c.demoSnapshot('MikeJones'),c.demoSnapshot('MikeBell'));
vm.runInContext("demoIdentity='admin@example.invalid'",c);
let admin=c.demoCall('getAdminState');
const p=admin.tables.Performances.records[0];
c.demoCall('saveAdminRecord',{table:'Performances',row:p.values._row,token:p.token,values:{...p.values,Status:'Cancelled'}});
assert(c.demoPublicData().events.filter(e=>e.performanceId===p.values.PerformanceID).every(e=>e.status==='Cancelled'));
assert.throws(()=>c.demoCall('saveAdminRecord',{table:'Performances',row:p.values._row,token:p.token,values:p.values}),/changed/);
c.demoCall('saveAdminRecord',{table:'Performances',row:0,values:{...p.values,PerformanceID:'new-date',Date:'2027-02-02',EndDate:'2027-02-02',Status:'Scheduled'}});
assert(c.demoCall('getEditorState').rows.filter(r=>r.performanceId==='new-date').every(r=>r.playerId===''&&r.status==='Open'));
const preview=c.demoCall('previewAdminRun');assert.equal(preview.rows.length,0);
const rule=admin.tables['Run Rules'].records[0];
c.demoCall('saveAdminRecord',{table:'Run Rules',row:rule.values._row,token:rule.token,values:{...rule.values,EndDate:'2026-12-15'}});
assert.throws(()=>c.demoCall('commitAdminRun',{token:preview.token}),/changed/);
const next=c.demoCall('previewAdminRun');assert(next.rows.length>0);c.demoCall('commitAdminRun',{token:next.token});
const newIds=new Set(next.rows.map(p=>p.PerformanceID));assert(c.demoCall('getEditorState').rows.filter(r=>newIds.has(r.performanceId)).every(r=>!r.playerId));
assert.equal(c.demoCall('previewAdminRun').rows.length,0);
const show=c.demoCall('getAdminState').tables.Shows.records[0];
c.demoCall('saveAdminRecord',{table:'Shows',row:show.values._row,token:show.token,values:{...show.values,Published:false}});
assert(c.demoPublicData().events.every(e=>e.showId!==show.values.ShowID));
assert(c.demoCall('getEditorState').rows.some(r=>r.showId===show.values.ShowID));
console.log('Reference demo: eligibility, admin boundaries, stale saves, isolation, conflicts, IDs, cancellation, blank seats, bulk preview and publication passed.');
